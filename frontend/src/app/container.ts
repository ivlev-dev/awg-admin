import type { Container } from "@ivlev-dev/silent-di";

import { AuthService } from "@/application/auth/service";
import { DevicesService } from "@/application/devices/service";
import { GroupsService } from "@/application/groups/service";
import { ImportService } from "@/application/import/service";
import { InterfacesService } from "@/application/interfaces/service";
import { NodesService } from "@/application/nodes/service";
import { SettingsService } from "@/application/settings/service";
import { StatsService } from "@/application/stats/service";
import { TariffsService } from "@/application/tariffs/service";
import { UsersService } from "@/application/users/service";
import { HttpApi } from "@/infrastructure/http";
import { DefaultApiConfig } from "@/infrastructure/http/config";
import { LiveStats } from "@/infrastructure/stats";
import { LocalTokenStore } from "@/infrastructure/storage";
import { createAppServices } from "./di";
import { Router } from "@/app/router";
import { Session } from "@/app/session";
import { ThemeStore } from "@/app/theme";
import { ToastStore } from "@/app/toast";

const services = createAppServices();
const tokens = services.tokens;
const api = new HttpApi(tokens, "/api/v1", services.backend);
const router = new Router();
const session = services.session;
const theme = new ThemeStore();
const toasts = new ToastStore();
const liveStats = new LiveStats(tokens);
const authService = services.auth;
const usersService = services.users;
const tariffsService = services.tariffs;
const groupsService = services.groups;
const nodesService = services.nodes;
const interfacesService = services.interfaces;
const devicesService = services.devices;
const statsService = services.stats;
const settingsService = services.settings;
const importService = services.import;

export function bindAppServices(container: Container): void {
  container.bind(LocalTokenStore, () => services.tokens);
  container.bind(DefaultApiConfig, () => services.config);
  container.bind(Session, () => session);
  container.bind(Router, () => router);
  container.bind(ThemeStore, () => theme);
  container.bind(ToastStore, () => toasts);
  container.bind(LiveStats, () => liveStats);
  container.bind(HttpApi, () => api);
  container.bind(AuthService, () => authService);
  container.bind(UsersService, () => usersService);
  container.bind(TariffsService, () => tariffsService);
  container.bind(GroupsService, () => groupsService);
  container.bind(NodesService, () => nodesService);
  container.bind(InterfacesService, () => interfacesService);
  container.bind(DevicesService, () => devicesService);
  container.bind(StatsService, () => statsService);
  container.bind(SettingsService, () => settingsService);
  container.bind(ImportService, () => importService);
}
